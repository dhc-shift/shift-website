-- 상시 커피챗 운영
-- Supabase SQL Editor에서 이 파일만 한 번 실행하세요.
--
-- 공개: coffee_chats (카드, 인원수, 상태, 일시, 후기)
-- 본인과 관리자: coffee_chat_applications (신청자, 질문)
-- 관리자만: coffee_chat_hosts (상대방 연락처, 동의 기록), coffee_chat_private (장소, 불발 사유)
--
-- 카드 1행이 회차 1개입니다. 다음 회차는 새 행으로 만듭니다.
-- 인원수와 모집 완료는 아래 트리거만 바꿉니다.

create table public.coffee_chat_hosts (
  id bigint generated by default as identity primary key,
  name text not null,
  kind text not null default '선배' check (kind in ('선배','대학원생','졸업생')),
  path_from text not null default '',
  path_to text not null default '',
  contact text not null default '',
  consent_note text not null,
  memo text not null default '',
  created_at timestamptz not null default now()
);

-- host_name 등은 공개용 복사본. 연락처가 있는 coffee_chat_hosts는 공개되지 않는다.
create table public.coffee_chats (
  id bigint generated by default as identity primary key,
  title text not null,
  host_id bigint references public.coffee_chat_hosts(id) on delete set null,
  host_name text not null default '',
  host_kind text not null default '',
  path_from text not null default '',
  path_to text not null default '',
  topics text[] not null default '{}',
  seek text not null default '',
  note text not null default '',
  good_for text[] not null default '{}',
  asks text[] not null default '{}',
  seats smallint not null default 3 check (seats between 2 and 3),
  status text not null default '모집 중' check (status in ('모집 중','모집 완료','연결 중','일정 확정','완료','불발')),
  applicant_count smallint not null default 0,
  round smallint not null default 1,
  scheduled_label text not null default '',
  review text not null default '',
  review_by text not null default '',
  created_at timestamptz not null default now()
);

create table public.coffee_chat_private (
  chat_id bigint primary key references public.coffee_chats(id) on delete cascade,
  place text not null default '',
  fail_reason text not null default ''
);

-- 학번, 이름, 이메일은 스냅샷. 명단에서 빠져도 기록은 남는다.
create table public.coffee_chat_applications (
  id bigint generated by default as identity primary key,
  chat_id bigint not null references public.coffee_chats(id) on delete cascade,
  user_id uuid references public.profiles(id) on delete set null,
  student_id text not null default '',
  member_name text not null default '',
  email text not null default '',
  question text not null default '',
  created_at timestamptz not null default now(),
  unique (chat_id, user_id)
);
create index coffee_chat_applications_user_idx on public.coffee_chat_applications (user_id);

alter table public.coffee_chat_hosts enable row level security;
alter table public.coffee_chats enable row level security;
alter table public.coffee_chat_private enable row level security;
alter table public.coffee_chat_applications enable row level security;

create policy "coffee chats public read" on public.coffee_chats for select to anon, authenticated using (true);
create policy "admins insert coffee chats" on public.coffee_chats for insert to authenticated with check (public.is_admin());
create policy "admins update coffee chats" on public.coffee_chats for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "admins delete coffee chats" on public.coffee_chats for delete to authenticated using (public.is_admin());

create policy "admins manage coffee chat hosts" on public.coffee_chat_hosts for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "admins manage coffee chat private" on public.coffee_chat_private for all to authenticated using (public.is_admin()) with check (public.is_admin());

create policy "read own coffee chat applications" on public.coffee_chat_applications for select to authenticated using (user_id = auth.uid() or public.is_admin());
create policy "apply to coffee chats" on public.coffee_chat_applications for insert to authenticated with check (user_id = auth.uid());
create policy "cancel coffee chat applications" on public.coffee_chat_applications for delete to authenticated using (user_id = auth.uid() or public.is_admin());

-- Supabase 기본 권한을 걷어내고 필요한 것만 준다.
revoke all on public.coffee_chat_hosts, public.coffee_chats, public.coffee_chat_private, public.coffee_chat_applications from anon, authenticated;
grant select on public.coffee_chats to anon, authenticated;
grant insert, update, delete on public.coffee_chats to authenticated;
grant select, insert, update, delete on public.coffee_chat_hosts, public.coffee_chat_private to authenticated;
grant select, delete on public.coffee_chat_applications to authenticated;
grant insert (chat_id, question) on public.coffee_chat_applications to authenticated;
grant usage, select on all sequences in schema public to authenticated;
grant all privileges on public.coffee_chat_hosts, public.coffee_chats, public.coffee_chat_private, public.coffee_chat_applications to service_role;

-- 신청: 카드 행을 잠가 동시 신청에도 정원을 넘지 않게 하고, 부원 정보는 서버가 채운다.
create function public.coffee_chat_before_apply()
returns trigger language plpgsql security definer set search_path = public
as $$
declare
  chat public.coffee_chats%rowtype;
  member public.member_stats%rowtype;
begin
  select * into chat from public.coffee_chats where id = new.chat_id for update;
  if not found then
    raise exception '커피챗을 찾을 수 없어요.';
  end if;
  if chat.status <> '모집 중' or chat.applicant_count >= chat.seats then
    raise exception '방금 자리가 모두 찼어요. 다음 회차가 열리면 다시 신청해주세요.';
  end if;
  select * into member from public.member_stats where lower(email) = lower(auth.jwt()->>'email');
  if not found then
    raise exception '부원 명단에서 확인되지 않아요. 운영진에게 문의해주세요.';
  end if;
  new.user_id := auth.uid();
  new.student_id := member.student_id;
  new.member_name := member.name;
  new.email := member.email;
  new.created_at := now();
  return new;
end;
$$;

create function public.coffee_chat_after_apply()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  update public.coffee_chats
    set applicant_count = applicant_count + 1,
        status = case when applicant_count + 1 >= seats then '모집 완료' else status end
    where id = new.chat_id;
  return null;
end;
$$;

-- 취소: 모집 완료까지는 본인이, 연결이 시작되면 운영진만.
create function public.coffee_chat_before_cancel()
returns trigger language plpgsql security definer set search_path = public
as $$
declare
  chat_status text;
begin
  select status into chat_status from public.coffee_chats where id = old.chat_id;
  if found and chat_status not in ('모집 중','모집 완료') and not public.is_admin() then
    raise exception '이미 연결이 시작됐어요. 취소는 운영진에게 카톡으로 알려주세요.';
  end if;
  return old;
end;
$$;

create function public.coffee_chat_after_cancel()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  update public.coffee_chats
    set applicant_count = greatest(applicant_count - 1, 0),
        status = case when status = '모집 완료' then '모집 중' else status end
    where id = old.chat_id;
  return null;
end;
$$;

create trigger coffee_chat_before_apply before insert on public.coffee_chat_applications
for each row execute function public.coffee_chat_before_apply();
create trigger coffee_chat_after_apply after insert on public.coffee_chat_applications
for each row execute function public.coffee_chat_after_apply();
create trigger coffee_chat_before_cancel before delete on public.coffee_chat_applications
for each row execute function public.coffee_chat_before_cancel();
create trigger coffee_chat_after_cancel after delete on public.coffee_chat_applications
for each row execute function public.coffee_chat_after_cancel();

notify pgrst, 'reload schema';
